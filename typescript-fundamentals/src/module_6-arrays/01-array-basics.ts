// Arrays
// Arrays in TypeScript is a collection of values of the same type stored in a single variable
// The values can be of any type, including primitive types (like number, string, boolean) or complex types (like objects or other arrays)

// Use of Arrays in QA domain
// - list of browsers
// - list of users
// - list of test cases
// - list of URLs
// - list of API response items
// - list of products in cart

// Declare of array using array literal syntax
const browsers: string[] = ['chromium', 'firefox', 'webkit'];

// Declare of array using new keyword and Array constructor
const statusCodes: Array<number> = [200, 201, 400, 404, 500];
