// Variables:
// Variables are used to store and retrieve data in our application

// Static Typing in TypeScript:
// TypeScript is a statically typed language, which means that the type of data will be decided at the compile time and not the run time
// Static typing helps us catch errors early in the development process at compile time and provides better code readability and maintainability.

// Type annotation:
// Type annotation is used to specify the type of a variable in TypeScript
// This helps catch type-related errors during development and provides better code readability
let age: number = 30;
let firstName: string = 'Rahul';
let isActive: boolean = true;

console.log(age); // Output: 30
console.log(firstName); // Output: Rahul
console.log(isActive); // Output: true

// undefined means a variable has been declared but has not been assigned a value
let a: undefined = undefined;

// null represents an intentional absence of any object value
let b: null = null;
