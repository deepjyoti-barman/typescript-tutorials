// TypeScript functions
// A function is a reusable block of code that performs a specific task
// Functions can take inputs, called parameters, and can return an output
// They help in organizing code, reducing repetition, and improving readability

// Functions are useful because (from QA stand-point):
// - avoid duplicate code
// - improve readability
// - make tests reusable
// - keep Playwright actions organized
// - help create page object methods

// Basic example
function greetUser(): void {
  console.log('Hello TypeScript functions!');
}

greetUser(); // Output: Hello TypeScript functions!
