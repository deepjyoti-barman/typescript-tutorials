// Ternary operator
// The ternary operator is a shorthand for the if-else statement in JavaScript and TypeScript
// It takes three operands: a condition, an expression to execute if the condition is true, and an expression to execute if the condition is false
// Syntax: condition ? valueIfTrue : valueIfFalse;
let isElementVisible = true;

let testResult = isElementVisible ? 'Element found' : 'Element missing';

console.log(testResult);

// Ternary is good for simple conditions
// For complex logic, use normal if else for readability
