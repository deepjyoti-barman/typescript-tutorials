// Looping statements
// Looping statements are used to repeat and run the block of code multiple times

// They are useful with working with:
// - arrays
// - lists of test data
// - multiple users
// - multiple browsers
// - multiple links
// - repeated checks

// for loop
// for loop is used when we know how many times we want to run the loop (exact no of iterations)
for (let retry = 1; retry <= 3; retry++) {
  console.log(`Retry attempt: ${retry}`);
}
